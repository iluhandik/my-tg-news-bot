import re

# Патерни реклами, спаму, казино, ставок, крипти та взаємного піару
AD_PATTERNS = [
    r"(?i)\b(erid|реклама|спонсор|партнерський)\b",
    r"(?i)(подпишись|підпишись|подписаться|підписатися)\s*(на|в)?\s*(канал|нас|резерв|чат)",
    r"(?i)(казино|ставки|1win|parimatch|слоти|гемблінг|бонус|промокод|виграш|бездеп)",
    r"(?i)(крипта|криптовалют|сигнали|трейдинг|btc|eth|usdt|заробіток|пасивний дохід)",
    r"(?i)(переходьте за посиланням|тисни сюди|дивіться тут|продовження за лінком)",
    r"(?i)(прислать новость|надіслати новину|зв'язок з адміном|наш бот|замовити рекламу)",
    r"(?i)(знижк|акці|розпродаж|купити зі знижкою|встигни забрати)",
    r"(?i)t\.me/\+[a-zA-Z0-9_-]+",  # приватні інвайт-лінки часто ведуть на рекламу треш-каналів
]

def is_advertisement(text: str) -> bool:
    """
    Жорсткий фільтр реклами.
    Повертає True, якщо пост є комерційною рекламою, піаром іншого каналу чи спамом.
    """
    if not text or len(text.strip()) < 20:
        return True

    clean = text.lower()

    # Перевірка за стоп-словами
    for pattern in AD_PATTERNS:
        if re.search(pattern, clean):
            return True

    # Якщо в пості дуже мало тексту, але є посилання чи бот — це 100% спам/реклама
    has_link = ("http" in clean or "t.me/" in clean or "@" in clean)
    if has_link and len(clean.split()) < 15:
        return True

    return False
