import re
import html

# Стоп-патерни: реклама, спам, казино, крипта, кол-центри, піар
AD_PATTERNS = [
    r"(?i)\b(erid|реклама|спонсор|партнерський)\b",
    r"(?i)(кол-центр|колцентр|офіс|шахрайськ.*офіс|100\s*000\s*грн|винагород|зароби.*на.*викритті)",
    r"(?i)(подпишись|підпишись|подписаться|підписатися)\s*(на|в)?\s*(канал|нас|резерв|чат|джерело)",
    r"(?i)(казино|ставки|1win|parimatch|слоти|гемблінг|бонус|промокод|виграш|бездеп|беттинг)",
    r"(?i)(крипта|криптовалют|сигнали|трейдинг|btc|eth|usdt|заробіток|пасивний дохід|схема)",
    r"(?i)(переходьте за посиланням|тисни сюди|дивіться тут|продовження за лінком|подробиці за лінком)",
    r"(?i)(прислать новость|надіслати новину|зв'язок з адміном|наш бот|замовити рекламу)",
    r"(?i)(знижк|акці|розпродаж|купити зі знижкою|встигни забрати)",
    r"(?i)t\.me/\+[a-zA-Z0-9_-]+",
]

# Беззмістовний спам, меми, зведення коментарів/лайків (як у пості про ЯНОС)
GIBBERISH_PATTERNS = [
    r"(?i)\b(лайків|лайки|коментарів|фанатів|противників|просвітів|харчок|ізонів)\b",
    r"(?i)\b(янос|мем|стікер|рейтинг.*людей.*лайків)\b",
]

# Рутинні тривоги без реальних подій (вибухів, прильотів, збиттів)
ROUTINE_ALERT_TRIGGERS = [
    r"(?i)\b(жовта тривога|повітряна тривога|оголошено тривогу|загроза бпла|пройдіть в укриття|відбій тривоги)\b",
    r"(?i)\b(активність ворожої авіації|загроза застосування балістики|зліт міг|тривога в областях)\b",
    r"(?i)\b(тривога в києві та областях|тривога в приазов|увага тривога)\b",
]

# Слова, які вказують, що подія РЕАЛЬНА (не просто сирена, а реальний факт чи бойова робота)
REAL_EVENT_MARKERS = [
    "вибух", "збит", "влучан", "приліт", "пожеж", "руйнуван", "поранен", "загинул",
    "удар", "пошкоджен", "атакован", "знищен", "ракета впала", "дрон поцілив"
]

def is_advertisement(text: str) -> bool:
    """
    Жорсткий фільтр реклами, безглуздих мемів та рутинних сповіщень про тривоги без подій.
    """
    if not text or len(text.strip()) < 20:
        return True

    clean = html.unescape(text).lower()

    # 1. Перевірка на рекламу
    for pattern in AD_PATTERNS:
        if re.search(pattern, clean):
            print(f"[ФІЛЬТР]: Відхилено рекламу: {pattern}")
            return True

    # 2. Перевірка на безглуздий спам (меми, лайки/коментарі/харчки)
    for pattern in GIBBERISH_PATTERNS:
        if re.search(pattern, clean):
            print(f"[ФІЛЬТР]: Відхилено безглуздий спам/мем: {clean[:40]}...")
            return True

    # 3. Перевірка на рутинні тривоги без реальних подій
    # Якщо це повідомлення про тривогу/сирену/загрозу, АЛЕ немає реальних наслідків (вибух, збиття, влучання)
    is_routine_alert = any(re.search(pat, clean) for pat in ROUTINE_ALERT_TRIGGERS)
    if is_routine_alert:
        has_real_event = any(marker in clean for marker in REAL_EVENT_MARKERS)
        if not has_real_event:
            print(f"[ФІЛЬТР]: Відхилено рутинне сповіщення про тривогу без наслідків: {clean[:50]}...")
            return True

    return False
